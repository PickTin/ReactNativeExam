-- Server database (SQLite). Applied automatically on every start; all statements are idempotent.

CREATE TABLE IF NOT EXISTS users (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    first_name  TEXT NOT NULL,
    last_name   TEXT NOT NULL,
    email       TEXT NOT NULL UNIQUE COLLATE NOCASE,
    password    TEXT NOT NULL,          -- bcrypt hash only, never the plain password
    created_at  TEXT NOT NULL           -- ISO 8601, UTC
);

CREATE TABLE IF NOT EXISTS offences (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    description  TEXT NOT NULL,
    url          TEXT,                  -- Cloudinary secure_url of the photo
    date         TEXT NOT NULL,         -- offence date, YYYY-MM-DD
    time         TEXT,                  -- offence time, HH:MM[:SS]
    user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    latitude     REAL,
    longitude    REAL,
    client_uuid  TEXT NOT NULL UNIQUE,  -- generated by the app; makes POST /offences idempotent
    created_at   TEXT NOT NULL,         -- when the record was created on the device
    updated_at   TEXT NOT NULL,
    deleted_at   TEXT                   -- soft delete marker
);

CREATE INDEX IF NOT EXISTS idx_offences_date ON offences(date);
CREATE INDEX IF NOT EXISTS idx_offences_user ON offences(user_id);
CREATE INDEX IF NOT EXISTS idx_offences_location ON offences(latitude, longitude);
